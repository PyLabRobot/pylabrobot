def make_v3_unit_wellplate(*, name: str) -> Plate:
  """The v3 unit's wellplate: 8 rows of 12 wells from ``V3_UNIT_A1``, 9 mm apart.

  Args:
    name: the wellplate's name.
  """
  wells = {}
  for row in range(8):
    for column in range(12):
      identifier = f"{chr(ord('A') + row)}{column + 1}"
      wells[identifier] = Well(name=f"{name}_{identifier}", size_x=7.0, size_y=7.0, size_z=0.0)
      wells[identifier].location = Coordinate(
        x=V3_UNIT_A1[0] + 9 * column - 3.5,
        y=PLATE_HOLDER_SIZE_Y - (V3_UNIT_A1[1] + 9 * row) - 3.5,
        z=0.0,
      )
  return Plate(
    name=name,
    size_x=PLATE_HOLDER_SIZE_X,
    size_y=PLATE_HOLDER_SIZE_Y,
    size_z=V3_UNIT_WELLPLATE_SIZE_Z,
    ordered_items=wells,
  )


Frame = Union[str, Tuple[Optional[float], ...]]


def expand_captured(*, captured: str) -> List[Frame]:
  """A captured stream, one frame each: a queued move as its targets, any other as its text."""
  frames: List[Frame] = []
  for line in captured.strip().splitlines():
    body, count = line.rsplit(" *", 1) if " *" in line else (line, "1")
    for frame in body.split(" | ") * int(count):
      if frame.startswith("68 "):
        frames.append(tuple(None if value == "-" else float(value) for value in frame.split()[1:]))
      else:
        frames.append(frame)
  return frames


def follow_queued_moves(*, driver) -> None:
  """Answer the head's position reads with where the queued moves sent each motor, from idle."""
  arm = driver.arm
  idle = arm._get_idle_targets()
  positions = {
    motor: compute_position(motor=motor, device_position=idle[motor]) for motor in (0, 1)
  }
  positions[2] = 0.0
  queue_move_item = driver._queue_move_item

  async def queue_and_follow(*, targets):
    for motor, (position, speed, _) in enumerate(targets):
      if speed:
        positions[motor] = compute_position(motor=motor, device_position=position)
    return await queue_move_item(targets=targets)

  async def request_arm_joint_state():
    return {motor: positions[motor] for motor in (0, 1)}

  async def request_measured_position(*, motor: int) -> float:
    return positions[motor]

  driver._queue_move_item = queue_and_follow
  arm._request_arm_joint_state = request_arm_joint_state
  arm._request_measured_position = request_measured_position


class PumpLink(RouteLink):
  """As ``RouteLink``, and answers each write to the pressure board empty and each queued valve
  state as a queued move was, as recorded; every line's status reads settled, as recorded."""

  def __init__(self, **kwargs):
    super().__init__(**kwargs)
    settled = CHIP_CONTROLLER_SETTLED[3]
    for controller in ("0000", "0100", "0200"):
      self.answers[(10, 16, bytes.fromhex(controller))] = [settled]

  async def write(self, data: bytes) -> int:
    _, board, command, payload = parse_frame(frame=data)
    if board == 10 and command in (11, 13, 15, 32, 34):
      self.answers.setdefault((board, command, payload), [b""])
    if (board, command) == (0, 65):
      self.answers.setdefault((board, command, payload), [bytes.fromhex(CLOSE_QUEUED_MOVE_REPLY)])
    return await super().write(data)


class V3PumpLink(V3Link):
  """As ``V3Link``, and answers what ``PumpLink`` does: the sequencer, each queued move and valve
  state, each write to the pressure board; every line settled, the vacuum reading 0."""

  def __init__(self, **kwargs):
    super().__init__(**kwargs)
    for command in (61, 62, 64):
      self.answers[(0, command, b"")] = [bytes.fromhex("0000")]
    for controller in ("0000", "0100", "0200"):
      self.answers[(10, 16, bytes.fromhex(controller))] = [CHIP_CONTROLLER_SETTLED[3]]
    self.answers[(10, 30, bytes.fromhex("0200"))] = [bytes(8)]

  async def write(self, data: bytes) -> int:
    _, board, command, payload = parse_frame(frame=data)
    if board == 10 and command in (11, 13, 15, 32, 34):
      self.answers.setdefault((board, command, payload), [b""])
    if (board, command) in ((0, 65), (0, 68)):
      self.answers.setdefault((board, command, payload), [bytes.fromhex(CLOSE_QUEUED_MOVE_REPLY)])
    return await super().write(data)


