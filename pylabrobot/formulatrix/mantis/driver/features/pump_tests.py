  async def test_a_clamp_that_does_not_release_still_releases_the_pressure(self):
    # A failed or cancelled unlock: the pressure is released all the same, then that is raised.
    for error in (MantisMotionError("stalled"), asyncio.CancelledError()):
      with self.subTest(error=type(error).__name__):
        driver = await self.set_up_wellplate(chip_type="low_volume_hi_fi")
        # The lock unlocks first, as captured; only the unlock after the wells fails.
        unlock_before = driver.plate_clamp.unlock

        async def unlock(error=error, unlock_before=unlock_before, driver=driver):
          if driver._wait_for_queue_item.await_count:
            raise error
          await unlock_before()

        driver.plate_clamp.unlock = unlock  # type: ignore[method-assign]
        with self.assertRaises(type(error)):
          await driver.pump.dispense(wells=[self.wellplate.get_item("A1")], volumes=[1.0])
        driver.plate_clamp.unlock = unlock_before  # type: ignore[method-assign]
        self.assertNotIn("64", self.sent_frames(link=self.link))
        self.assertEqual(
          self.sent_frames(link=self.link)[-8:],
          [
            "10/13 00000000",
            "10/13 01000000",
            "10/13 02000000",
            "10/15 0000",
            "10/34 0000204e",
            "10/32 0000204e",
            "10/34 00000000",
            "10/32 00000000",
          ],
        )

  async def test_a_cancelled_dispense_stops_then_releases_the_clamp_and_the_pressure(self):
    driver = await self.set_up_wellplate(chip_type="low_volume_hi_fi")
    driver._wait_for_queue_item.side_effect = asyncio.CancelledError
    with self.assertRaises(asyncio.CancelledError):
      await driver.pump.dispense(wells=[self.wellplate.get_item("A1")], volumes=[1.0])
    self.assert_stopped_and_released()
    sent = self.sent(self.link)
    self.assertEqual(sent[sent.index(HALT[-1]) :].count(RELEASE), 1)


