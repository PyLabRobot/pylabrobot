"""Controller and handling faults from the StoreX remote-operation protocol."""


class StoreXError(RuntimeError):
  """A device fault retaining its numeric code and triggering command."""

  def __init__(self, code: str, command: str, message: str):
    self.code = code
    self.command = command
    self.message = message
    super().__init__(f"{command}: {code}: {message}")


class StoreXProtocolError(RuntimeError):
  """A missing or malformed reply; reconnect before issuing another command."""


